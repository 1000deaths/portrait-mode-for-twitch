// Compiles styles/*.scss into src/styles.js so the content script can inject
// them without needing web-accessible resources. Run with `npm run build`.
import { compile } from 'sass';
import { readdirSync, writeFileSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const stylesDir = join(root, 'styles');

const out = {};
for (const file of readdirSync(stylesDir).filter(f => f.endsWith('.scss')).sort()) {
	const { css } = compile(join(stylesDir, file), { style: 'expanded' });
	out[basename(file, '.scss')] = css;
}

const banner = `// GENERATED by tools/build-styles.mjs from styles/*.scss. Do not edit by hand.
// Stylesheets derived from FrankerFaceZ (Apache-2.0). See NOTICE.
`;

writeFileSync(
	join(root, 'src', 'styles.js'),
	`${banner}'use strict';\n\nconst TPM_STYLES = Object.freeze(${JSON.stringify(out, null, '\t')});\n`
);

console.log(`Wrote src/styles.js (${Object.keys(out).join(', ')})`);
